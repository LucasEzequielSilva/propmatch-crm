-- DEAL ROOM / OPERACIONES — BORRADOR DE DISEÑO. NO APLICADO.
--
-- Está en `drafts/` y no en `migrations/` a propósito: no debe aplicarse sin
-- revisarlo con Lucas. Adaptado al esquema REAL de la base de la app:
--   · existen: agencies, agency_members(role text), properties, users,
--     is_agency_member(uuid), storage.buckets
--   · NO existen: contacts, opportunities, profiles, tasks (viven en el CRM,
--     en localStorage). Por eso las partes guardan sus datos acá mismo y solo
--     guardan una referencia SIN FK a la entidad del CRM (`crm_*_ref`).
--
-- Reglas de este diseño:
--   · Todo cuelga de agency_id y se filtra con is_agency_member().
--   · Lo financiero (pagos, comisiones) y los datos legales de las partes se
--     restringen a admin de la agencia o al responsable de la operación.
--   · Timeline y auditoría de firma: solo se agregan filas, nunca se editan.
--   · Documentos: bucket PRIVADO, acceso con URL firmada de corta duración.
--   · No hay billetera ni procesador de pagos: los pagos son un registro.
--   · Firma electrónica agnóstica del proveedor: las tablas guardan estado y
--     auditoría; quién firma lo decide la capa SignatureProvider del código.
-- ════════════════════════════════════════════════════════════════════════════

-- ── 0. Helpers de permisos ──────────────────────────────────────────────────

create or replace function public.is_agency_admin(p_agency_id uuid)
returns boolean
language sql stable security definer
set search_path to 'public', 'pg_temp'
as $$
  select exists (
    select 1 from public.agency_members
    where agency_id = p_agency_id and user_id = auth.uid() and role = 'admin'
  );
$$;
revoke execute on function public.is_agency_admin(uuid) from public, anon;
grant execute on function public.is_agency_admin(uuid) to authenticated;

-- ¿Puede ver/operar lo financiero de esta operación? Admin o responsable.
create or replace function public.can_manage_deal_money(p_deal_id uuid)
returns boolean
language sql stable security definer
set search_path to 'public', 'pg_temp'
as $$
  select exists (
    select 1 from public.deals d
    where d.id = p_deal_id
      and (public.is_agency_admin(d.agency_id) or d.responsible_user_id = auth.uid())
  );
$$;
revoke execute on function public.can_manage_deal_money(uuid) from public, anon;
grant execute on function public.can_manage_deal_money(uuid) to authenticated;

create or replace function public.block_mutation()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  raise exception '% es solo de agregado (%): no se edita ni se borra', tg_table_name, tg_op;
end $$;

create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.updated_at = now();
  return new;
end $$;


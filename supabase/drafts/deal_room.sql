create policy deal_splits_select on public.deal_commission_splits for select to authenticated
  using (public.is_agency_admin(agency_id) or user_id = auth.uid());
create policy deal_splits_admin_write on public.deal_commission_splits for all to authenticated
  using (public.is_agency_admin(agency_id)) with check (public.is_agency_admin(agency_id));


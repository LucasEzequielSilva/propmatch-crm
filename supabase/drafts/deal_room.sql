-- Máquina de estados: avanzar un paso, volver uno, o cancelar desde cualquier
-- etapa abierta. Una cancelada se reabre en negociación. Una completada es final.
create or replace function public.deals_enforce_stage()
returns trigger language plpgsql set search_path = public, pg_temp as $$
declare
  flow text[] := array['negociacion','reserva','documentacion','contrato',
                       'firma_pendiente','firmada','cierre','completada'];
  a int; b int;
begin
  new.updated_at := now();
  if tg_op = 'UPDATE' and new.stage is distinct from old.stage then
    a := array_position(flow, old.stage);
    b := array_position(flow, new.stage);
    if old.stage = 'completada' then
      raise exception 'Una operación completada no cambia de etapa';
    elsif new.stage = 'cancelada' then
      null;                                            -- desde cualquier etapa abierta
    elsif old.stage = 'cancelada' and new.stage = 'negociacion' then
      null;                                            -- reabrir
    elsif a is null or b is null or abs(a - b) <> 1 then
      raise exception 'Salto de etapa no permitido: % -> %', old.stage, new.stage;
    end if;
    new.stage_since := now();
    if new.stage = 'completada' then new.closed_at := now(); end if;
  end if;
  return new;
end $$;
create trigger deals_enforce_stage before update on public.deals
  for each row execute function public.deals_enforce_stage();
create trigger deals_enforce_stage_ins before insert on public.deals
  for each row execute function public.deals_enforce_stage();


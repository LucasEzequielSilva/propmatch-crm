-- Todo cambio de etapa queda registrado solo, sin depender del front.
create or replace function public.deals_log_stage()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.stage is distinct from old.stage then
    insert into public.deal_events (agency_id, deal_id, type, title, data, actor_id)
    values (new.agency_id, new.id, 'stage_changed',
            'Etapa: ' || old.stage || ' → ' || new.stage,
            jsonb_build_object('from', old.stage, 'to', new.stage), auth.uid());
  end if;
  return new;
end $$;
create trigger deals_log_stage after update on public.deals
  for each row execute function public.deals_log_stage();

